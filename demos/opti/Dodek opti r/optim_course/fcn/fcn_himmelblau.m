function [J,g,H] = fcn_himmelblau(x)
x1 = x(1);
x2 = x(2);

J = (x1^2 + x2 - 11)^2 + (x1 + x2^2 - 7)^2;

g = [4*x1*(x1^2 + x2 - 11) + 2*(x1 + x2^2 - 7);
     2*(x1^2 + x2 - 11) + 4*x2*(x1 + x2^2 - 7)];

H = [12*x1^2 + 4*x2 - 42,       4*x1 + 4*x2;
     4*x1 + 4*x2,               4*x1 + 12*x2^2 - 26];

end